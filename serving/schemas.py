"""Pydantic schemas shared by the API (serving/app.py) and the batch CLI (predict_batch.py).

Validation policy, defined once here:
  - total_charges may be null or omitted ONLY when tenure_months == 0 (a new
    customer not yet billed); it is then treated as 0.0, exactly as in training.
    Every other field is required.
  - Numbers: no NaN/infinity; physically impossible values are rejected
    (negatives, or values above the hard caps below). Values that are possible
    but outside the training range are accepted and reported as warnings
    (see serving/scoring.py).
  - Unknown extra fields are rejected.

Two variants differ only where the two entry points must differ:
  - API (CustomerFeatures / PredictRequest): strict JSON types, and categorical
    values must be in ALLOWED_CATEGORIES (unseen values -> HTTP 422).
  - Batch (BatchRecord): CSV cells are text, so numbers are parsed from strings
    ("12" -> 12); categorical values may be any non-empty string, and unseen
    ones are scored with a row-level warning (see serving/scoring.py).
"""

from typing import Annotated, Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, create_model, model_validator

from src.data_pipeline import ALLOWED_CATEGORIES, CATEGORICAL_FEATURES

# Hard caps: anything above these is treated as impossible, not just unusual.
TENURE_MAX_MONTHS = 1200                 # 100 years
MONTHLY_CHARGES_MAX = 10_000.0           # far above any real consumer plan
TOTAL_CHARGES_MAX = MONTHLY_CHARGES_MAX * TENURE_MAX_MONTHS

CustomerId = Annotated[str, Field(min_length=1, max_length=64, description="Record ID, echoed in the output")]


class _NumericFieldsAndRules(BaseModel):
    """Numeric inputs and cross-field rules common to both variants."""

    model_config = ConfigDict(strict=True, extra="forbid")

    tenure_months: int = Field(ge=0, le=TENURE_MAX_MONTHS, description="Months as a customer")
    monthly_charges: float = Field(ge=0, le=MONTHLY_CHARGES_MAX, allow_inf_nan=False)
    total_charges: Optional[float] = Field(
        default=None, ge=0, le=TOTAL_CHARGES_MAX, allow_inf_nan=False,
        description="May be null only when tenure_months is 0",
    )

    @model_validator(mode="after")
    def total_charges_null_only_for_new_customers(self):
        if self.total_charges is None and self.tenure_months != 0:
            raise ValueError("total_charges may be null only when tenure_months is 0")
        return self


def _choice(feature: str):
    """Literal type that accepts exactly the allowed values of one feature."""
    return Literal[tuple(ALLOWED_CATEGORIES[feature])]


# API variant: each categorical field accepts only its allowed values.
CustomerFeatures = create_model(
    "CustomerFeatures", __base__=_NumericFieldsAndRules,
    **{f: (_choice(f), ...) for f in CATEGORICAL_FEATURES},
)


class PredictRequest(CustomerFeatures):
    """One customer to score through the API, with its identifiers."""

    customer_id: CustomerId
    request_id: Optional[str] = Field(
        default=None, min_length=1, max_length=64,
        description="Caller's request ID; generated by the server if omitted",
    )


class _LenientNumericFieldsAndRules(_NumericFieldsAndRules):
    # Same fields and rules; lax typing because CSV cells arrive as text.
    model_config = ConfigDict(strict=False, extra="forbid")


# Batch variant: any non-empty category string; unseen values are warned about, not rejected.
BatchRecord = create_model(
    "BatchRecord", __base__=_LenientNumericFieldsAndRules,
    customer_id=(CustomerId, ...),
    **{f: (str, Field(min_length=1)) for f in CATEGORICAL_FEATURES},
)


class PredictResponse(BaseModel):
    request_id: str
    customer_id: str
    churn_probability: float = Field(description="Model probability, or a fallback estimate (see source)")
    churn_prediction: bool
    threshold: Optional[float] = Field(description="Probability cut-off applied; null when the heuristic rule decided")
    decision_rule: str = Field(description="How churn_prediction was decided")
    source: Literal["model", "fallback_heuristic", "fallback_prior_rate"]
    fallback_reason: Optional[str] = None
    warnings: list[str] = Field(default_factory=list)


class HealthResponse(BaseModel):
    status: Literal["ok", "unavailable"]
    model_loaded: bool
    threshold: Optional[float] = None
    fallback_probability: Optional[float] = None
    simulated_failure: Optional[str] = Field(default=None, description="Test-only failure switch; null = off")
    detail: Optional[str] = None
